// Command zonesgen writes pkg/sitetime/zones_gen.go - the canonical IANA
// time zones (the tz database's Zone entries, not its Link aliases) of the
// world's regions, from a tzdata.zi file (default
// /usr/share/zoneinfo/tzdata.zi). Run through go generate in pkg/sitetime.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"log"
	"os"
	"sort"
	"strings"
)

// regions - the area prefixes offered; Etc/* and Factory are left out.
var regions = []string{"Africa", "America", "Antarctica", "Asia", "Atlantic", "Australia", "Europe", "Indian", "Pacific"}

func main() {
	src := flag.String("tzdata", "/usr/share/zoneinfo/tzdata.zi", "tzdata.zi to read")
	out := flag.String("o", "zones_gen.go", "file to write")
	flag.Parse()

	f, err := os.Open(*src)
	if err != nil {
		log.Fatal(err)
	}
	defer func() { _ = f.Close() }()
	version := ""
	var zones []string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if v, ok := strings.CutPrefix(line, "# version "); ok {
			version = v
		}
		fields := strings.Fields(line)
		if len(fields) < 2 || fields[0] != "Z" {
			continue
		}
		area, _, _ := strings.Cut(fields[1], "/")
		for _, r := range regions {
			if area == r {
				zones = append(zones, fields[1])
			}
		}
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	sort.Strings(zones)

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by zonesgen from tzdata %s; DO NOT EDIT.\n\npackage sitetime\n\n", version)
	b.WriteString("// zones - the canonical IANA time zones of the world's regions.\nvar zones = []string{\n")
	for _, z := range zones {
		fmt.Fprintf(&b, "\t%q,\n", z)
	}
	b.WriteString("}\n")
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
}
