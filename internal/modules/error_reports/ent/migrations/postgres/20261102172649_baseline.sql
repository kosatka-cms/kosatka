-- Create "error_reports" table
CREATE TABLE "error_reports" ("id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY, "user_id" bigint NULL, "page_url" character varying NOT NULL, "selected_text" text NOT NULL, "comment" text NULL, "client_ip" character varying NULL, "user_agent" character varying NULL, "created_at" timestamptz NOT NULL DEFAULT (CURRENT_TIMESTAMP), "resolved_at" timestamptz NULL, PRIMARY KEY ("id"));
-- Create index "error_reports_created_at" to table: "error_reports"
CREATE INDEX "error_reports_created_at" ON "error_reports" ("created_at" DESC);
-- Create index "error_reports_user_id" to table: "error_reports"
CREATE INDEX "error_reports_user_id" ON "error_reports" ("user_id");
-- Create index "error_reports_resolved_at" to table: "error_reports"
CREATE INDEX "error_reports_resolved_at" ON "error_reports" ("resolved_at");
