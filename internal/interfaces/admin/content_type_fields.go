// pathFieldID parses the "field_id" path value; field routes carry both
// the content type ID ({id}, see PathID) and the field ID ({field_id}).
func (c *Controller) pathFieldID(r *http.Request) (int, bool) {
	id, err := strconv.Atoi(r.PathValue("field_id"))
	if err != nil || id <= 0 {
		return 0, false
	}
	return id, true
}

// contentTypeField - the content type ({id}) and its field ({field_id})
// the URL names; false - answered already: 404 for a bad ID, a missing
// type or field, or a field of another type (it is never changed through
// this type's pages), 500 for a failure.
func (c *Controller) contentTypeField(w http.ResponseWriter, r *http.Request) (*entity.ContentTypeDef, *entity.FieldInstanceDef, bool) {
	id, ok := c.PathID(r)
	if !ok {
		c.RenderNotFound(w, r)
		return nil, nil, false
	}
	fieldID, ok := c.pathFieldID(r)
	if !ok {
		c.RenderNotFound(w, r)
		return nil, nil, false
	}
	contentType, err := c.contentTypeService.ContentTypeByID(r.Context(), id)
	if err != nil {
		c.RenderLoadFailure(w, r, err, "loading the content type", "contentTypeID", id)
		return nil, nil, false
	}
	field, err := c.contentTypeService.FieldByID(r.Context(), fieldID)
	if err != nil {
		c.RenderLoadFailure(w, r, err, "loading the field", "fieldID", fieldID)
		return nil, nil, false
	}
	if field.ContentTypeID != id {
		c.RenderNotFound(w, r)
		return nil, nil, false
	}
	return contentType, field, true
}

// typeFields - the fields of content type typeID by ID: field IDs and
// group IDs a form of that type posts must be among them (the URL names
// the type, the form names the fields; a field of another type is
// refused, not changed).
func (c *Controller) typeFields(ctx context.Context, typeID int) (map[int]entity.FieldInstanceDef, error) {
	fields, err := c.contentTypeService.FieldsByContentTypeID(ctx, typeID)
	if err != nil {
		return nil, err
	}
	own := make(map[int]entity.FieldInstanceDef, len(fields))
	for _, f := range fields {
		own[f.ID] = f
	}
	return own, nil
}

// linkHostSuggestions - the sites the enabled modules' link formatters
// show (service.FieldFormatter.Hosts), space-separated, each set once: a
// link field's allowed sites to fill in.
func linkHostSuggestions(ctx context.Context) []string {
	var out []string
	for _, f := range service.FieldFormatters(entity.FieldTypeLink) {
		if f.Hosts == nil {
			continue
		}
		if hosts := strings.Join(f.Hosts(ctx), " "); hosts != "" && !slices.Contains(out, hosts) {
			out = append(out, hosts)
		}
	}
	return out
}

// ownGroup - groupID is nil or a group field among own.
func ownGroup(own map[int]entity.FieldInstanceDef, groupID *int) bool {
	if groupID == nil {
		return true
	}
	g, ok := own[*groupID]
	return ok && g.FieldType == entity.FieldTypeGroup
}

// ContentTypeFieldCreate handles POST /admin/config/content-types/{id}/fields.
func (c *Controller) ContentTypeFieldCreate(w http.ResponseWriter, r *http.Request) {
	id, ok := c.PathID(r)
	if !ok {
		c.RenderNotFound(w, r)
		return
	}
	redirectBase := "/admin/config/content-types/" + strconv.Itoa(id) + "/fields"
	// return_to: the detail tab's "Create group" form also posts here but
	// returns to its own tab. Only this content type's own fields sub-path is
	// accepted (no open redirect). Its presence also skips the redirect to
	// the new field's edit page.
	rt := r.FormValue("return_to")
	hasReturnTo := strings.HasPrefix(rt, redirectBase)
	if hasReturnTo {
		redirectBase = rt
	}
	if r.Method != http.MethodPost {
		http.Redirect(w, r, redirectBase, http.StatusSeeOther)
		return
	}
	ctx := r.Context()

	machineName := strings.ToLower(strings.TrimSpace(r.FormValue("machine_name")))
	label := strings.TrimSpace(r.FormValue("label"))
	fieldType := r.FormValue("field_type")
	if label == "" {
		http.Redirect(w, r, redirectBase+"?error=empty", http.StatusSeeOther)
		return
	}
	if !isValidFieldType(fieldType) {
		http.Redirect(w, r, redirectBase+"?error=invalid-type", http.StatusSeeOther)
		return
	}
	ft := entity.ContentTypeFieldType(fieldType)

	// machine_name is optional on both create forms; if empty it is generated
	// from the label (transliterated, snake_case rather than slug.Generate's
	// hyphens).
	autoGeneratedMachineName := false
	if machineName == "" {
		machineName = strings.ReplaceAll(slug.Generate(label), "-", "_")
		if machineName == "" {
			machineName = "field"
		}
		autoGeneratedMachineName = true
	}
	// "field_" is always prepended, whether machine_name was typed or generated.
	if !strings.HasPrefix(machineName, "field_") {
		machineName = "field_" + machineName
	}
	// No vocabulary/allowed values/widget validation here: the create form
	// only collects the type and the immutable multiple flag; everything else
	// is configured on the new field's edit page (see the redirect below).

	required := r.FormValue("required") == "1"
	hiddenInForm := r.FormValue("hidden_in_form") == "1"
	sortOrder, _ := strconv.Atoi(r.FormValue("sort_order"))

	// usable_in_form/usable_in_detail matter only for a FieldTypeGroup (see
	// entity.FieldInstanceDef.UsableInForm); read unconditionally.
	usableInForm := r.FormValue("usable_in_form") == "1"
	usableInDetail := r.FormValue("usable_in_detail") == "1"

	// Display settings (ShowOnDetail/ShowLabel/DisplayOrder) belong to the
	// detail tab. A new field starts visible on the detail page with its label,
	// at the end of the order.
	newField := entity.FieldInstanceDef{
		ContentTypeID:   id,
		MachineName:     machineName,
		Label:           label,
		FieldType:       ft,
		Required:        required,
		HiddenInForm:    hiddenInForm,
		ShowOnDetail:    true,
		ShowLabel:       true,
		ShowLabelInList: true,
		SortOrder:       sortOrder,
		DisplayOrder:    sortOrder,
		FormGroupID:     formGroupIDFromForm(r),
		UsableInForm:    usableInForm,
		UsableInDetail:  usableInDetail,
		Config:          fieldConfigFromForm(r, ft),
		WidgetConfig:    fieldWidgetConfigFromForm(r, ft),
	}
	if own, err := c.typeFields(ctx, id); err != nil || !ownGroup(own, newField.FormGroupID) {
		c.LogFailure(err, "checking the new field's group", "contentTypeID", id)
		http.Redirect(w, r, redirectBase+"?error=invalid", http.StatusSeeOther)
		return
	}
	created, err := c.contentTypeService.CreateField(ctx, newField)
	// An auto-generated machine_name was never seen by the admin, so on a
	// collision retry with a numeric suffix instead of reporting an error. A
	// typed machine_name still reports the error below.
	if err != nil && autoGeneratedMachineName && errors.Is(err, service.ErrFieldStorageMachineNameTaken) {
		base := machineName
		for i := 2; i <= 20; i++ {
			newField.MachineName = fmt.Sprintf("%s_%d", base, i)
			created, err = c.contentTypeService.CreateField(ctx, newField)
			if err == nil || !errors.Is(err, service.ErrFieldStorageMachineNameTaken) {
				c.LogFailure(err, "creating the field")
				break
			}
		}
	}
	if err != nil {
		if errors.Is(err, service.ErrFieldStorageMachineNameTaken) {
			http.Redirect(w, r, redirectBase+"?error=machine-name-taken", http.StatusSeeOther)
			return
		}
		if errors.Is(err, service.ErrBlocksInFieldSet) {
			http.Redirect(w, r, redirectBase+"?error=blocks-in-field-set", http.StatusSeeOther)
			return
		}
		c.LogFailure(err, "error creating content type field", "contentTypeID", id)
		http.Redirect(w, r, redirectBase+"?error=create", http.StatusSeeOther)
		return
	}
	// Forms with return_to go back to their tab; the general "Add field" row
	// goes to the new field's edit page to configure the rest (widget, allowed
	// values, vocabulary, target type, group scope).
	if !hasReturnTo {
		editURL := fmt.Sprintf("/admin/config/content-types/%d/fields/%d/edit?created=1", id, created.ID)
		http.Redirect(w, r, editURL, http.StatusSeeOther)
		return
	}
	http.Redirect(w, r, redirectBase+"?success=1", http.StatusSeeOther)
}

// ContentTypeFieldEdit renders GET
// /admin/config/content-types/{id}/fields/{field_id}/edit - one field's
// settings (label, type-specific config, required, hidden, group scope);
// submits to ContentTypeFieldUpdate.
func (c *Controller) ContentTypeFieldEdit(w http.ResponseWriter, r *http.Request) {
	ctx := r.Context()
	contentType, field, ok := c.contentTypeField(w, r)
	if !ok {
		return
	}
	fieldID := field.ID

	vocabularies, err := c.taxonomyService.Vocabularies(ctx)
	if err != nil {
		c.LogFailure(err, "error listing vocabularies for field edit page")
	}
	valueCount, err := c.contentTypeService.FieldValueCount(ctx, fieldID)
	if err != nil {
		c.LogFailure(err, "error counting field values for field edit page", "fieldID", fieldID)
	}

	var defaultImageURL string
	var defaultFileURL, defaultFileName string
	if field.DefaultImageID != nil {
		switch field.FieldType {
		case entity.FieldTypeImage:
			if file, ferr := c.fileRepo.ByID(ctx, *field.DefaultImageID); ferr != nil {
				c.LogFailure(ferr, "error loading field's default image", "fieldID", fieldID, "defaultImageID", *field.DefaultImageID)
			} else {
				defaultImageURL = imageurl.Original(*file).URI
			}
		case entity.FieldTypeFile:
			if file, ferr := c.fileRepo.ByID(ctx, *field.DefaultImageID); ferr != nil {
				c.LogFailure(ferr, "error loading field's default file", "fieldID", fieldID, "defaultImageID", *field.DefaultImageID)
			} else {
				defaultFileURL = imageurl.Original(*file).URI
				defaultFileName = file.OriginalFilename
				if defaultFileName == "" {
					defaultFileName = path.Base(file.URI)
				}
			}
		}
	}

	data := c.getAdminData(r)
	data["title"] = i18n.T(r.Context(), "Field \"@field\": @type", "@field", field.Label, "@type", contentType.Label)
	data["pageSEO"] = entity.PageSEO{Title: i18n.T(r.Context(), "Field @field - @type - Admin panel", "@field", field.Label, "@type", contentType.Label)}
	data["contentType"] = contentType
	markFieldSetMenu(data, contentType.Embedded)
	data["field"] = field
	data["activeTab"] = "fields"
	data["fieldWidgets"] = fieldWidgets
	data["listWidgets"] = listWidgets
	data["taxonomyWidgets"] = taxonomyWidgets
	data["vocabularies"] = vocabularies
	data["fieldValueCount"] = valueCount
	data["defaultImageURL"] = defaultImageURL
	data["defaultFileURL"] = defaultFileURL
	data["defaultFileName"] = defaultFileName
	// What the type's settings show besides the field (adminFieldType.data).
	if typeData := adminFieldTypes[field.FieldType].data; typeData != nil {
		typeData(ctx, c, data)
	}
	if textFormats, tfErr := c.textFormatService.TextFormats(ctx); tfErr != nil {
		c.LogFailure(tfErr, "error listing text formats for field edit page")
	} else {
		data["textFormats"] = textFormats
	}
	if c.dateFormats != nil {
		if formats, dfErr := c.dateFormats.DateFormats(ctx); dfErr != nil {
			c.LogFailure(dfErr, "error listing date formats for field edit page")
		} else {
			data["dateFormats"] = formats
		}
	}
	data["error"] = r.URL.Query().Get("error")
	data["uploadErrorDetail"] = r.URL.Query().Get("upload_error")
	data["success"] = r.URL.Query().Get("success") == "1"
	data["created"] = r.URL.Query().Get("created") == "1"
	data["cardinalityChanged"] = r.URL.Query().Get("cardinality") == "1"
	c.AddFormSectionsData(ctx, data, interfaces.FormField, strconv.Itoa(fieldID))

	c.RenderOrFail(w, r, "admin/content-types/field_edit.html", data)
}

// ContentTypeFieldUpdate handles POST /admin/config/content-types/{id}/fields/{field_id}.
// field_type is immutable (changing it would orphan the typed value table
// holding the data). Redirects back to ContentTypeFieldEdit.
func (c *Controller) ContentTypeFieldUpdate(w http.ResponseWriter, r *http.Request) {
	id, ok := c.PathID(r)
	if !ok {
		c.RenderNotFound(w, r)
		return
	}
	listRedirect := "/admin/config/content-types/" + strconv.Itoa(id) + "/fields"
	if r.Method != http.MethodPost {
		http.Redirect(w, r, listRedirect, http.StatusSeeOther)
		return
	}
	ctx := r.Context()
	_, existing, ok := c.contentTypeField(w, r)
	if !ok {
		return
	}
	fieldID := existing.ID
	editRedirect := fmt.Sprintf("%s/%d/edit", listRedirect, fieldID)

	label := strings.TrimSpace(r.FormValue("label"))
	if label == "" {
		http.Redirect(w, r, editRedirect+"?error=empty", http.StatusSeeOther)
		return
	}
	required := r.FormValue("required") == "1"
	hiddenInForm := r.FormValue("hidden_in_form") == "1"

	// defaultImageID - FieldTypeImage/FieldTypeFile only (see
	// entity.FieldInstanceDef.DefaultImageID): kept unless this submission
	// uploads a replacement or checks "Remove".
	defaultImageID := existing.DefaultImageID
	if existing.FieldType == entity.FieldTypeImage || existing.FieldType == entity.FieldTypeFile {
		if file, header, ferr := r.FormFile("default_image"); ferr == nil {
			currentUser, uerr := c.GetCurrentUser(r)
			if uerr != nil || currentUser == nil {
				_ = file.Close()
				http.Redirect(w, r, editRedirect+"?error=auth", http.StatusSeeOther)
				return
			}
			var contentType string
			if def, err := c.contentTypeService.ContentTypeByID(ctx, id); err == nil {
				contentType = def.MachineName
			} else {
				c.LogFailure(err, "loading the content type", "contentTypeID", id)
			}
			tokens := interfaces.FieldUploadTokens(contentType, currentUser.ID)
			var newID int
			var saveErr error
			// The default file or image shows on every item without one
			// of its own: always public, even for a field keeping its
			// files private.
			field := *existing
			field.WidgetConfig = maps.Clone(existing.WidgetConfig)
			delete(field.WidgetConfig, "private_files")
			if existing.FieldType == entity.FieldTypeImage {
				newID, saveErr = interfaces.SaveFieldImageWithPolicy(ctx, &c.fileUploadService, c.fileRepo, file, header, tokens, field)
			} else {
				newID, saveErr = interfaces.SaveFieldFileWithPolicy(ctx, &c.fileUploadService, c.fileRepo, file, header, tokens, field)
			}
			if saveErr != nil {
				c.LogFailure(saveErr, "error saving field's default upload", "fieldID", fieldID)
				http.Redirect(w, r, editRedirect+"?error=default-image&upload_error="+url.QueryEscape(i18n.ErrorText(r.Context(), saveErr)), http.StatusSeeOther)
				return
			}
			defaultImageID = &newID
		} else if r.FormValue("remove_default_image") == "1" {
			defaultImageID = nil
		}
	}

	// The edit form never submits "multiple" (the field's own page,
	// ContentTypeFieldCardinality, changes it), so carry the stored value
	// forward into the rebuilt config.
	config := fieldConfigFromForm(r, existing.FieldType)
	if existing.FieldType.AllowsMultiple() && existing.Multiple() {
		config["multiple"] = true
	}
	// symmetric - editable on the edit page, but only together with multiple.
	if existing.FieldType == entity.FieldTypeReference && existing.Multiple() && r.FormValue("symmetric") == "1" {
		config["symmetric"] = true
	}
	// widgetConfig - the per-content-type config (see
	// fieldWidgetConfigFromForm); always read fresh from the submission.
	widgetConfig := fieldWidgetConfigFromForm(r, existing.FieldType)
	// The type's own checks (adminFieldType.check): the edit page is where
	// a vocabulary, list values, a widget, blocks' sets are set.
	if check := adminFieldTypes[existing.FieldType].check; check != nil {
		errKey, detail, err := check(ctx, c, r, *existing, config, widgetConfig)
		if err != nil {
			c.LogFailure(err, "error checking the field's settings", "fieldID", fieldID)
			http.Redirect(w, r, editRedirect+"?error=update", http.StatusSeeOther)
			return
		}
		if errKey != "" {
			target := editRedirect + "?error=" + errKey
			if detail != "" {
				target += "&upload_error=" + url.QueryEscape(detail)
			}
			http.Redirect(w, r, target, http.StatusSeeOther)
			return
		}
	}

	// Ordering, display and group membership (SortOrder/ShowOnDetail/
	// ShowLabel/DisplayOrder/ParentGroupID/FormGroupID) are not set here:
	// UpdateField doesn't write those columns; they are managed by the tabs'
	// drag-and-drop actions. UsableInForm/UsableInDetail are submitted by this
	// form (they matter only for a group field).
	_, err := c.contentTypeService.UpdateField(ctx, entity.FieldInstanceDef{
		ID:             fieldID,
		ContentTypeID:  id,
		FieldStorageID: existing.FieldStorageID,
		MachineName:    existing.MachineName,
		Label:          label,
		FieldType:      existing.FieldType,
		Required:       required,
		HiddenInForm:   hiddenInForm,
		DefaultImageID: defaultImageID,
		UsableInForm:   r.FormValue("usable_in_form") == "1",
		UsableInDetail: r.FormValue("usable_in_detail") == "1",
		Config:         config,
		WidgetConfig:   widgetConfig,
		DateFormat:     fieldDateFormatFromForm(r, *existing),
	})
	if err == nil {
		err = interfaces.SaveFormSections(ctx, interfaces.FormField, strconv.Itoa(fieldID), r)
	}
	if err != nil {
		c.LogFailure(err, "error updating content type field", "fieldID", fieldID)
		http.Redirect(w, r, editRedirect+"?error=update", http.StatusSeeOther)
		return
	}
	if c.dateFormats != nil {
		c.dateFormats.Reset()
	}
	http.Redirect(w, r, editRedirect+"?success=1", http.StatusSeeOther)
}

// ContentTypeFieldDeleteConfirm renders GET
// /admin/config/content-types/{id}/fields/{field_id}/delete - a
// confirmation page showing how many values are stored for the field,
// since deleting it drops them irrecoverably. Posts to
// ContentTypeFieldDelete.
func (c *Controller) ContentTypeFieldDeleteConfirm(w http.ResponseWriter, r *http.Request) {
	ctx := r.Context()
	contentType, field, ok := c.contentTypeField(w, r)
	if !ok {
		return
	}
	id, fieldID := contentType.ID, field.ID

	data := c.getAdminData(r)
	data["title"] = i18n.T(r.Context(), "Delete field \"@field\": @type", "@field", field.Label, "@type", contentType.Label)
	data["pageSEO"] = entity.PageSEO{Title: i18n.T(r.Context(), "Delete field @field - @type - Admin panel", "@field", field.Label, "@type", contentType.Label)}
	data["contentType"] = contentType
	markFieldSetMenu(data, contentType.Embedded)
	data["field"] = field
	data["activeTab"] = "fields"

	// A group stores no values, so its value count (always 0) would be
	// misleading; what can block deleting it is its member fields
	// (parent_group_id/form_group_id).
	if field.FieldType == entity.FieldTypeGroup {
		memberLabels, err := c.groupMemberLabels(ctx, id, fieldID)
		if err != nil {
			c.LogFailure(err, "error counting group members for field delete page", "fieldID", fieldID)
		}
		data["groupMemberLabels"] = memberLabels
	} else {
		valueCount, err := c.contentTypeService.FieldValueCount(ctx, fieldID)
		if err != nil {
			c.LogFailure(err, "error counting field values for field delete page", "fieldID", fieldID)
		}
		data["fieldValueCount"] = valueCount
	}

	// storageUsage - whether the field leaves the catalog with this
	// instance (entity.FieldStorageUsage; counted before the deletion, so
	// Instances includes this one).
	if usage, err := c.contentTypeService.FieldStorageUsage(ctx, field.FieldStorageID); err != nil {
		c.LogFailure(err, "error checking field storage usage for field delete page", "fieldID", fieldID)
	} else {
		data["storageUsage"] = usage
	}

	c.RenderOrFail(w, r, "admin/content-types/field_delete.html", data)
}

// groupMemberLabels returns the labels of the fields of contentTypeID
// whose ParentGroupID or FormGroupID points at groupFieldID - the fields
// that block deleting the group (RESTRICT foreign keys).
func (c *Controller) groupMemberLabels(ctx context.Context, contentTypeID, groupFieldID int) ([]string, error) {
	fields, err := c.contentTypeService.FieldsByContentTypeID(ctx, contentTypeID)
	if err != nil {
		return nil, err
	}
	var labels []string
	for _, f := range fields {
		if (f.ParentGroupID != nil && *f.ParentGroupID == groupFieldID) ||
			(f.FormGroupID != nil && *f.FormGroupID == groupFieldID) {
			labels = append(labels, f.Label)
		}
	}
	return labels, nil
}

// ContentTypeFieldDelete handles POST /admin/config/content-types/{id}/fields/{field_id}/delete.
func (c *Controller) ContentTypeFieldDelete(w http.ResponseWriter, r *http.Request) {
	id, ok := c.PathID(r)
	if !ok {
		c.RenderNotFound(w, r)
		return
	}
	redirectBase := "/admin/config/content-types/" + strconv.Itoa(id) + "/fields"
	if r.Method != http.MethodPost {
		http.Redirect(w, r, redirectBase, http.StatusSeeOther)
		return
	}
	ctx := r.Context()
	_, field, ok := c.contentTypeField(w, r)
	if !ok {
		return
	}
	fieldID := field.ID
	// A group still referenced by members can't be deleted (RESTRICT foreign
	// keys on parent_group_id/form_group_id). Checked up front to show a clear
	// reason instead of DeleteField's generic error.
	if field.FieldType == entity.FieldTypeGroup {
		memberLabels, merr := c.groupMemberLabels(ctx, id, fieldID)
		if merr != nil {
			c.LogFailure(merr, "error checking group members before delete", "fieldID", fieldID)
		} else if len(memberLabels) > 0 {
			http.Redirect(w, r, redirectBase+"?error=delete_group_has_members", http.StatusSeeOther)
			return
		}
	}

	if err := c.contentTypeService.DeleteField(ctx, fieldID); err != nil {
		c.LogFailure(err, "error deleting content type field", "fieldID", fieldID)
		http.Redirect(w, r, redirectBase+"?error=delete", http.StatusSeeOther)
		return
	}
	http.Redirect(w, r, redirectBase+"?deleted=1", http.StatusSeeOther)
}
